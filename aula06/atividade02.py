    print(f'\nRODADA {i + 1}')
    num = float(input('numero: '))

    dobro = num * 2
    triplo = num * 3 
    quadrado = num ** 2

    print(f'O dobro é: {dobro:.2f}')
    print(f'O triplo é: {triplo:.2f}')
    print(f'O quadrado é: {quadrado:.2f}')



